import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/crates_for_host.dart';
import '../helpers/temp_dir.dart';

/// 관제 2026-11-07 (native-memory-safety): refusal 8 named every crate the
/// lock names and offered `cargo fetch --locked` — the Surface fetched 29
/// crates for Linux, the Mac and Android with the four its build needed,
/// and nobody had allowed those. The list is now one platform's, worked out
/// from what the machine holds (tool/crates_for_host.dart says why cargo
/// cannot give it offline).
///
/// ⚠️What these cannot hold is that the walk is cargo's: that was measured
/// on master the same day, against `cargo metadata --filter-platform` for
/// six platforms (Windows x64 and ARM, Linux, the Mac, Android, iOS) — equal
/// crate for crate, 241 to 257 of the lock's 330.
void main() {
  final windows = TargetPlatform('x86_64-pc-windows-msvc', [
    'target_os="windows"',
    'target_family="windows"',
    'target_pointer_width="64"',
    'windows',
    'debug_assertions',
  ]);

  group('a platform takes a dependency', () {
    test('declared for every platform', () {
      expect(windows.takes(null), isTrue);
    });

    test('declared for its own triple, and no other', () {
      expect(windows.takes('x86_64-pc-windows-msvc'), isTrue);
      expect(windows.takes('aarch64-linux-android'), isFalse);
    });

    test('declared for a cfg its own cfg makes true', () {
      expect(windows.takes('cfg(windows)'), isTrue);
      expect(windows.takes('cfg(unix)'), isFalse);
      expect(windows.takes('cfg(target_os = "windows")'), isTrue);
      expect(windows.takes('cfg(target_os = "android")'), isFalse);
      expect(
        windows.takes('cfg(all(target_os = "windows", not(target_env)))'),
        isTrue,
      );
      expect(
        windows.takes('cfg(all(windows, target_pointer_width = "32"))'),
        isFalse,
      );
      expect(windows.takes('cfg(any(unix, windows))'), isTrue);
      expect(
        windows.takes('cfg(any(target_os = "macos", target_os = "ios"))'),
        isFalse,
      );
      expect(windows.takes('cfg(not(windows))'), isFalse);
    });

    test('and a cfg it cannot read is not guessed at', () {
      expect(() => windows.takes('cfg(maybe(windows))'), throwsFormatException);
    });
  });

  group('the crates a build takes', () {
    const registry =
        'source = "registry+https://github.com/rust-lang/crates.io-index"';
    String lockOf(List<String> packages) =>
        '# This file is automatically @generated by Cargo.\nversion = 4\n'
        '${packages.map((p) => '\n[[package]]\n$p').join()}';
    final members = {
      'engine 0.1.0': <Declared>[
        (crate: 'everywhere', kind: 'normal', target: null),
        (crate: 'android', kind: 'normal', target: 'cfg(target_os = "android")'),
        (crate: 'tested', kind: 'dev', target: null),
      ],
    };
    final lock = lockPackages(
      lockOf([
        'name = "engine"\nversion = "0.1.0"\ndependencies = [\n'
            ' "android",\n "everywhere",\n "tested",\n]\n',
        'name = "everywhere"\nversion = "1.0.0"\n$registry\ndependencies = [\n'
            ' "linux",\n "own_tests",\n "plain",\n "nested 2.0.0",\n]\n',
        'name = "android"\nversion = "1.0.0"\n$registry\n',
        'name = "tested"\nversion = "1.0.0"\n$registry\n',
        'name = "linux"\nversion = "1.0.0"\n$registry\n',
        'name = "own_tests"\nversion = "1.0.0"\n$registry\n',
        'name = "plain"\nversion = "1.0.0"\n$registry\n',
        'name = "nested"\nversion = "1.0.0"\n$registry\n',
        'name = "nested"\nversion = "2.0.0"\n$registry\n',
      ]),
    );
    final everywhere = <Declared>[
      (crate: 'linux', kind: 'normal', target: 'cfg(target_os = "linux")'),
      (crate: 'own_tests', kind: 'dev', target: null),
      (crate: 'plain', kind: 'normal', target: null),
      (crate: 'nested', kind: 'build', target: null),
    ];

    test('reaches what every edge for this platform reaches, and only that',
        () {
      expect(
        cratesFor(
          lock,
          members,
          (p) => p.name == 'everywhere' ? everywhere : const [],
          windows,
        ),
        {'everywhere-1.0.0', 'tested-1.0.0', 'plain-1.0.0', 'nested-2.0.0'},
        reason: 'not android (a member\'s, for Android), not linux (a '
            'crate\'s, for Linux), not own_tests (a crate\'s own tests '
            'are never built), not nested 1.0.0 (no edge reaches it)',
      );
    });

    test('a crate whose declarations are not here has every edge walked', () {
      expect(
        cratesFor(lock, members, (_) => null, windows),
        containsAll(['linux-1.0.0', 'own_tests-1.0.0']),
        reason: 'what cannot be ruled out is listed',
      );
    });
  });

  group('the index entry a crate was resolved from', () {
    late Directory index;
    setUp(() => index = Directory.systemTemp.createTempSync('crates-index'));
    tearDown(() => deleteTempQuietly(index));

    void entry(String at, String name, List<String> versions) {
      final file = File('${index.path}/index.crates.io-0/.cache/$at/$name')
        ..createSync(recursive: true);
      file.writeAsBytesSync([
        3, 2, 0, 0, 0, ...'etag: "x"'.codeUnits, 0,
        for (final json in versions) ...[
          ...'v'.codeUnits, 0, ...json.codeUnits, 0,
        ],
      ]);
    }

    test('is read at the folder cargo keeps it in, by its version', () {
      entry('cp/al', 'cpal', [
        '{"name":"cpal","vers":"0.17.0","deps":[]}',
        '{"name":"cpal","vers":"0.18.2","deps":[{"name":"alsa",'
            '"target":"cfg(target_os = \\"linux\\")","kind":"normal"},'
            '{"name":"sample","package":"dasp_sample","target":null,'
            '"kind":null}]}',
      ]);
      expect(indexDependencies(index, 'cpal', '0.18.2'), [
        (crate: 'alsa', kind: 'normal', target: 'cfg(target_os = "linux")'),
        (crate: 'dasp_sample', kind: 'normal', target: null),
      ]);
      expect(indexDependencies(index, 'cpal', '0.17.0'), isEmpty);
    });

    test('of a short name, where cargo keeps those', () {
      entry('1', 'a', ['{"name":"a","vers":"1.0.0","deps":[]}']);
      entry('2', 'ab', ['{"name":"ab","vers":"1.0.0","deps":[]}']);
      entry('3/a', 'abc', ['{"name":"abc","vers":"1.0.0","deps":[]}']);
      for (final name in ['a', 'ab', 'abc']) {
        expect(indexDependencies(index, name, '1.0.0'), isEmpty);
      }
    });

    test('and is null where this machine never saw one', () {
      expect(indexDependencies(index, 'cpal', '0.18.2'), isNull);
    });
  });
}
